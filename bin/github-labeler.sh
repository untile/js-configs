#!/bin/bash

# Generates .github/labeler.yml (actions/labeler v5+ format) with one label per package.

set -euo pipefail

# Define the monorepo packages directory.
packages_dir="packages"

# Create the .github directory if it does not exist.
mkdir -p .github

# Create or clear the labeler.yml file.
echo "# Auto-generated by bin/github-labeler.sh" > .github/labeler.yml

# Iterate through subdirectories in 'packages', sorted so the output is stable.
for package in $(find "$packages_dir" -mindepth 1 -maxdepth 1 -type d | sort); do
  package_name=$(basename "$package")
  echo "Generating entry for package: $package_name"

  # Add entry for the package to the labeler.yml file.
  cat <<EOT >> .github/labeler.yml

# Label for package $package_name.
$package_name:
  - changed-files:
      - any-glob-to-any-file: $package/**
EOT
done

echo "Generated .github/labeler.yml based on monorepo packages."
